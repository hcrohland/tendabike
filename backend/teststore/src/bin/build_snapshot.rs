//! Rebuilds `src/prepopulated_data.rs` from the canonical workshop store.
//!
//! Run: `cargo run -p tb_teststore --bin build-snapshot`

use tb_teststore::build_workshop_store;

#[tokio::main(flavor = "current_thread")]
async fn main() -> anyhow::Result<()> {
    let store = build_workshop_store().await?;
    let snap = store.snapshot();

    println!(
        "Parts: {}, attachments: {}, usages: {}, activities: {}",
        snap.parts.len(),
        snap.attachments.len(),
        snap.usages.len(),
        snap.activities.len()
    );

    let json = serde_json::to_string_pretty(&snap)?;

    let content = format!(
        "//! Prepopulated store data for tests.\n\
         //! Generated by the `build-snapshot` bin.\n\
         //! Regenerate: cargo run -p tb_teststore --bin build-snapshot\n\
         \n\
         /// Formatted JSON snapshot of the prepopulated store.\n\
         /// This is a pretty-printed JSON string that gets deserialized by TestStore::prepopulated().\n\
         pub const SNAPSHOT_JSON: &str = r#\"{}\"#;\n",
        json
    );

    let path = concat!(env!("CARGO_MANIFEST_DIR"), "/src/prepopulated_data.rs");
    std::fs::write(path, &content)?;
    println!("Wrote {}", path);

    Ok(())
}
